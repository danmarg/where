// Fuzzing (src/jvmFuzz; see docs/fuzzing.md). One target per parser of attacker-controlled bytes;
// each throws only typed WhereExceptions and leaves its fixed state unchanged.
val fuzzCompilation = kotlin.jvm().compilations.getByName("fuzz")
val fuzzCorpusDir = layout.projectDirectory.dir("src/jvmFuzz/corpus")

// Every committed corpus input through every target: a fast regression run for CI.
val fuzzCorpusTest by tasks.registering(Test::class) {
    description = "Replays the committed fuzz corpus through each fuzz target."
    group = "verification"
    testClassesDirs = fuzzCompilation.output.classesDirs
    classpath = fuzzCompilation.output.allOutputs + fuzzCompilation.runtimeDependencyFiles
    useJUnit()
    inputs.dir(fuzzCorpusDir)
    systemProperty("fuzz.corpus", fuzzCorpusDir.asFile.absolutePath)
}

// ./gradlew :shared:fuzz -Pfuzz.target=DecryptMessage [-Pfuzz.seconds=600]
// Runs one target under Jazzer, growing build/fuzz/<target>/corpus from the committed seeds. A
// finding fails the task and leaves its input in build/fuzz/<target>/.
tasks.register<JavaExec>("fuzz") {
    description = "Fuzzes one target with Jazzer (-Pfuzz.target=<name>, -Pfuzz.seconds=<n>)."
    group = "verification"
    val target = providers.gradleProperty("fuzz.target")
    val seconds = providers.gradleProperty("fuzz.seconds").orElse("60")
    val outDir = layout.buildDirectory.dir("fuzz")
    classpath = fuzzCompilation.output.allOutputs + fuzzCompilation.runtimeDependencyFiles
    mainClass.set("com.code_intelligence.jazzer.Jazzer")
    // Jazzer attaches its instrumentation agent to this JVM at startup.
    jvmArgs("-XX:+EnableDynamicAgentLoading", "-Xss8m")
    argumentProviders.add(
        CommandLineArgumentProvider {
            val name = target.orNull ?: throw GradleException("pass -Pfuzz.target=<name>, e.g. DecryptMessage")
            val work = outDir.get().dir(name).asFile
            val corpus = work.resolve("corpus").apply { mkdirs() }
            listOf(
                "--target_class=net.af0.where.e2ee.fuzz.${name}Fuzzer",
                "--instrumentation_includes=net.af0.where.**:kotlinx.serialization.**:kotlin.io.encoding.**",
                "--reproducer_path=${work.absolutePath}",
                "-artifact_prefix=${work.absolutePath}/",
                "-max_total_time=${seconds.get()}",
                "-max_len=4096",
                "-timeout=10",
                "-rss_limit_mb=4096",
                "-print_final_stats=1",
                corpus.absolutePath,
                fuzzCorpusDir.dir(name).asFile.absolutePath,
            )
        },
    )
}

// Adds well-formed seeds for every target to src/jvmFuzz/corpus (see SeedCorpus).
tasks.register<JavaExec>("generateFuzzSeeds") {
    description = "Writes the fuzz seed corpus from well-formed inputs."
