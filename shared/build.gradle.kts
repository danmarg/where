// Test vector files compiled into commonTest as string constants: Kotlin/Native tests have no
// resource loading, and the same files have to be read on the JVM and on iOS. Wycheproof
// (src/commonTest/resources/wycheproof) runs in CryptoPrimitivesVectorTest, whose HMAC backends
// differ by platform; the golden transcript (src/commonTest/resources/vectors) in
// GoldenTranscriptTest.
fun registerVectorSources(
    taskName: String,
    resourceDir: String,
    objectName: String,
) = tasks.register(taskName) {
    val inputDir = layout.projectDirectory.dir("src/commonTest/resources/$resourceDir")
    val outputDir = layout.buildDirectory.dir("generated/$resourceDir/kotlin")
    inputs.dir(inputDir)
    outputs.dir(outputDir)
    doLast {
        fun literal(s: String) =
            buildString {
                append('"')
                for (c in s) {
                    when {
                        c == '"' || c == '\\' || c == '$' -> append('\\').append(c)
                        c == '\n' -> append("\\n")
                        c.code < 0x20 || c.code > 0x7e -> append("\\u%04x".format(c.code))
                        else -> append(c)
                    }
                }
                append('"')
            }
        val files = inputDir.asFile.listFiles { f -> f.name.endsWith(".json") }!!.sortedBy { it.name }
        val out = outputDir.get().asFile.resolve("net/af0/where/e2ee/$objectName.kt")
        out.parentFile.mkdirs()
        out.writeText(
            buildString {
                appendLine("// Generated by :shared:$taskName from src/commonTest/resources/$resourceDir.")
                appendLine("package net.af0.where.e2ee")
                appendLine()
                appendLine("internal object $objectName {")
                appendLine("    fun read(name: String): String =")
                appendLine("        when (name) {")
                files.forEachIndexed { i, f -> appendLine("            ${literal(f.name)} -> f$i()") }
                appendLine("            else -> throw IllegalArgumentException(\"no file \$name in $resourceDir\")")
                appendLine("        }")
                files.forEachIndexed { i, f ->
                    appendLine()
                    // Chunked: a JVM string constant holds at most 65535 bytes.
                    appendLine("    private fun f$i(): String =")
                    appendLine("        buildString {")
                    f.readText().chunked(16_000).forEach { appendLine("            append(${literal(it)})") }
                    appendLine("        }")
                }
                appendLine("}")
            },
        )
    }
}

